type Req = EventDef['requires'];
type Fx = Effect[];

const out = (
  id: string,
  text: string,
  effects: Fx,
  weight = 1,
  statBias?: Outcome['statBias'],
  relBias?: Outcome['relBias'],
  actorTraitBias?: Outcome['actorTraitBias'],
): Outcome => ({
  id,
  text,
  effects,
  weight,
  ...(statBias ? { statBias } : {}),
  ...(relBias ? { relBias } : {}),
  ...(actorTraitBias ? { actorTraitBias } : {}),
});

const stat = (s: Extract<Effect, { type: 'stat' }>['stat'], delta: number): Effect => ({ type: 'stat', stat: s, delta });
